"""Writes src/lib/icons.ts: Phosphor (MIT) icons as SVG path data.

Usage: python3 -I tools/icons.py   (from the project folder, standard library only)
Add a name to ICONS (Phosphor's own kebab-case name) and run it again.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE / 'phosphor'))
from glyphs import Font, path  # noqa: E402

ICONS = sorted(set('''
airplane-tilt app-window apple-logo arrow-left arrow-right arrow-up-right arrows-clockwise
bank barcode bell briefcase browser buildings building-office calculator calendar-check car
caret-down caret-left caret-right certificate chalkboard-teacher chart-bar chart-line chats chat-circle-text
check check-circle clipboard-text clock cloud cloud-sun coins cooking-pot copy desktop device-mobile
drop envelope-simple facebook-logo factory file-text flask fork-knife gear globe google-play-logo
handshake hand-coins headset house identification-card image info instagram-logo lifebuoy lightning
link linkedin-logo list lock magnifying-glass map-pin map-trifold medal megaphone monitor moon note
notebook package paper-plane-tilt phone phone-call plant play-circle plus presentation-chart printer
quotes receipt rocket-launch scales seal-check share-network shield-check shopping-cart sliders sparkle
stack star storefront sun suitcase target timer translate truck user user-circle users users-three
video-camera wallet warehouse warning-circle whatsapp-logo wifi-high wrench x youtube-logo
'''.split()))


def main():
    names = json.loads((HERE / 'phosphor/names.json').read_text())
    font = Font(str(HERE / 'phosphor/PhosphorRegular.ttf'))
    lines = []
    for name in ICONS:
        cp = names.get(name)
        gid = font.cmap.get(int(cp, 16)) if cp else None
        if gid is None:
            sys.exit(f'No Phosphor icon called {name}')
        key = name if name.isidentifier() else f"'{name}'"
        lines.append(f"  {key}: '{path(font, font.contours(gid))}',")
    out = HERE.parent / 'src/lib/icons.ts'
    out.write_text(
        '// Generated by tools/icons.py from Phosphor Regular (MIT). Do not edit by hand.\n'
        '// Each value is SVG path data in a 256 unit box.\n'
        'export const icons = {\n' + '\n'.join(lines) + '\n} as const;\n\n'
        'export type IconName = keyof typeof icons;\n')
    print(len(ICONS), 'icons written to', out)


main()
